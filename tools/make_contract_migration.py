#!/usr/bin/env python3
"""Builds supabase/migrations/0010_people_templates.sql from the markdown
templates in docs/contracts/. The markdown files stay the source of truth;
re-run this after editing them:  python3 tools/make_contract_migration.py
"""
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
body = (root / "docs/contracts/director-service-agreement.md").read_text()
notes = (root / "docs/contracts/director-service-agreement.notes.md").read_text()
keys = sorted(set(re.findall(r"\{\{(\w+)\}\}", body)))
fields = [{"key": k, "label": k.replace("_", " ").capitalize()} for k in keys]

sql = f"""-- 0010: People and HR templates (Settings > People and HR).
-- job_roles: reusable job descriptions. contract_templates: versioned
-- contract wording with {{{{merge_fields}}}}. Admin only, 2FA required.
-- GENERATED by tools/make_contract_migration.py from docs/contracts/.
-- The seeded director service agreement is a DRAFT awaiting solicitor review.

create table if not exists public.job_roles (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  summary text not null default '',
  duties text not null default '',
  reports_to text not null default '',
  place_of_work text not null default '',
  typical_hours text not null default '',
  status text not null default 'draft' check (status in ('draft','active','retired')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contract_templates (
  id uuid primary key default gen_random_uuid(),
  key text not null,
  name text not null,
  employee_type text not null default 'director'
    check (employee_type in ('director','permanent','part_time','fixed_term','apprentice','casual')),
  version integer not null default 1,
  status text not null default 'draft'
    check (status in ('draft','solicitor_review','approved','retired')),
  body_md text not null,
  notes_md text not null default '',
  fields jsonb not null default '[]'::jsonb,
  reviewed_by text,
  reviewed_on date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (key, version)
);

alter table public.job_roles enable row level security;
alter table public.contract_templates enable row level security;

drop policy if exists job_roles_admin on public.job_roles;
create policy job_roles_admin on public.job_roles
  for all using (public.current_role() = 'admin' and public.mfa_ok())
  with check (public.current_role() = 'admin' and public.mfa_ok());

drop policy if exists contract_templates_admin on public.contract_templates;
create policy contract_templates_admin on public.contract_templates
  for all using (public.current_role() = 'admin' and public.mfa_ok())
  with check (public.current_role() = 'admin' and public.mfa_ok());

insert into public.job_roles (title, summary, duties, reports_to, place_of_work, typical_hours, status)
select 'Managing Director',
  $ags_s$Leads AGS Decorating & Refurbishment Services. Responsible for strategy, financial performance, client and builder relationships, quality, health and safety, and the people who work for the business.$ags_s$,
  $ags_d$- Set and deliver the company strategy, budget and growth plans.
- Own financial performance: pricing, margins, cash flow and reporting.
- Lead client, builder and supplier relationships and win new work.
- Make sure projects are delivered to the AGS standard, on time and on budget.
- Be accountable for health and safety, insurance and legal compliance.
- Recruit, manage and develop employees and sub-contractors, and make sure they are engaged lawfully.
- Perform the duties of a director under the Companies Act 2006.$ags_d$,
  'The Board', 'Head office, with travel to client sites', 'Monday to Friday, 8:00 to 17:00, plus the hours the role needs', 'draft'
where not exists (select 1 from public.job_roles where title = 'Managing Director');

insert into public.contract_templates (key, name, employee_type, version, status, body_md, notes_md, fields)
select 'director_service_agreement', 'Managing Director service agreement', 'director', 1, 'draft',
  $ags_body${body}$ags_body$,
  $ags_notes${notes}$ags_notes$,
  $ags_fields${json.dumps(fields)}$ags_fields$::jsonb
where not exists (select 1 from public.contract_templates where key = 'director_service_agreement' and version = 1);
"""
out = root / "supabase/migrations/0010_people_templates.sql"
out.write_text(sql)
print("wrote", out, len(sql), "bytes;", len(keys), "fields")


# ---- 0012: sub-contractor agreement ------------------------------------
sub_body = (root / "docs/contracts/subcontractor-agreement.md").read_text()
sub_notes = (root / "docs/contracts/subcontractor-agreement.notes.md").read_text()
sub_keys = sorted(set(re.findall(r"\{\{(\w+)\}\}", sub_body)))
sub_fields = [{"key": k, "label": k.replace("_", " ").capitalize()} for k in sub_keys]
sql2 = f"""-- 0012: Seeds the sub-contractor agreement template (version 1, DRAFT).
-- GENERATED by tools/make_contract_migration.py from docs/contracts/.
-- Needs 0010 (contract_templates) and 0011 (the subcontractor template type).

insert into public.contract_templates (key, name, employee_type, version, status, body_md, notes_md, fields)
select 'subcontractor_agreement', 'Sub-contractor agreement (painters and decorators)', 'subcontractor', 1, 'draft',
  $ags_body${sub_body}$ags_body$,
  $ags_notes${sub_notes}$ags_notes$,
  $ags_fields${json.dumps(sub_fields)}$ags_fields$::jsonb
where not exists (select 1 from public.contract_templates where key = 'subcontractor_agreement' and version = 1);
"""
out2 = root / "supabase/migrations/0012_subcontractor_agreement.sql"
out2.write_text(sql2)
print("wrote", out2, len(sub_keys), "fields")
